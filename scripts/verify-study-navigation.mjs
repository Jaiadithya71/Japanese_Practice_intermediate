import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { createStudyHistory } from '../js/study-history.js';
const source=fs.readFileSync('js/study.js','utf8');
const functions=['previousStudyCard','nextStudyCard','skipCard','gradeCard'].map(name=>source.match(new RegExp(`export function ${name}\\([^)]*\\) \\{[\\s\\S]*?^\\}`, 'm'))[0].replace('export ', '')).join('\n');
const a={key:'a'}, b={key:'b'}, c={key:'c'};
const state={sessionItems:[a,b,c],sessionIdx:0,sessionSkipped:0,sessionRight:0,sessionTotalAnswered:0,cardFlipped:true,studyMode:'flashcard'};
let writes=0;
const ctx=vm.createContext({state,studyHistory:createStudyHistory(),reviewPhase:'test',canGradeReview:(p,f)=>p==='test'&&f,formatItemKey:i=>i.key,updateItemStats:()=>writes++,renderCard:()=>{}});
vm.runInContext(functions,ctx);
const run=s=>vm.runInContext(s,ctx);
run('previousStudyCard()');assert.equal(state.sessionIdx,0);
run('nextStudyCard()');assert.equal(state.sessionIdx,1);assert.equal(writes,0);assert.equal(state.sessionSkipped,0);
run('previousStudyCard()');assert.equal(state.sessionIdx,0);
state.cardFlipped=true;run('gradeCard(3)');assert.equal(writes,1);assert.equal(state.sessionTotalAnswered,1);
run('previousStudyCard()');state.cardFlipped=true;run('gradeCard(4)');assert.equal(writes,1);assert.equal(state.sessionTotalAnswered,1);assert.equal(state.sessionRight,1);
run('nextStudyCard()');run('skipCard()');assert.equal(state.sessionSkipped,1);
run('previousStudyCard()');run('skipCard()');assert.equal(state.sessionSkipped,1);
run('previousStudyCard()');state.cardFlipped=true;run('gradeCard(1)');assert.equal(writes,2);assert.equal(state.sessionSkipped,0);
assert.equal(state.sessionItems.length,4);
state.sessionIdx=3;state.cardFlipped=true;run('gradeCard(3)');assert.equal(writes,3);assert.equal(state.sessionTotalAnswered,3);
state.sessionIdx=3;run('nextStudyCard()');assert.equal(state.sessionIdx,3);
state.sessionItems=[{key:'a'}];state.sessionIdx=0;state.cardFlipped=true;run('gradeCard(3)');assert.equal(writes,4);
assert.match(source,/Already graded:/);
assert.match(source,/if \(previous\).*previous.disabled = state.sessionIdx <= 0/);
console.log('Navigation: browse no writes, first/last bounds, no duplicate grading/skips, skipped-to-graded correction, Again new attempt, fresh-session reset passed.');
const html=fs.readFileSync('index.html','utf8');
assert.ok(html.indexOf('id="study-skip-row"') > html.indexOf('id="study-card-container"'));
assert.ok(html.indexOf('id="study-skip-row"') < html.indexOf('id="grade-controls"'));
assert.match(source,/getElementById\('study-skip-row'\)\?\.append\(topAction\)/);
console.log('Previous/Next and Learn action share the bottom action area before grading.');
assert.match(source,/button.disabled = !state.cardFlipped \|\| !!priorOutcome\?\.grade/);
assert.match(source,/classList.toggle\('test-action-layout', testLayout\)/);
console.log('Test grade controls stay visible and are disabled before reveal or after prior grading.');

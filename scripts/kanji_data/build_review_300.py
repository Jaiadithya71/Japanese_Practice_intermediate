def make_ruby(kanji, word, reading):
    # If the word starts or ends with kana, wrap the kanji portion appropriately
    # For simple single kanji words:
    if word == kanji:
        return f"<ruby>{kanji}<rt>{reading}</rt></ruby>"
    
    # If word starts with kanji and ends with okurigana:
    # e.g. 悪い (わるい) -> <ruby>悪<rt>わる</rt></ruby>い
    # We can check okurigana match at the end
    if len(word) > 1 and word.startswith(kanji):
        okurigana = word[1:]
        if reading.endswith(okurigana):
            kanji_reading = reading[:-len(okurigana)]
            return f"<ruby>{kanji}<rt>{kanji_reading}</rt></ruby>{okurigana}"

    # Prefix tilde ~
    if word.startswith("〜"):
        base_word = word[1:]
        return f"〜<ruby>{base_word}<rt>{reading}</rt></ruby>"
    if word.endswith("〜"):
        base_word = word[:-1]
        return f"<ruby>{base_word}<rt>{reading}</rt></ruby>〜"

    # Prefix お e.g. お茶
    if word.startswith("お") and word[1:] == kanji:
        return f"お<ruby>{kanji}<rt>{reading[1:] if reading.startswith('お') else reading}</rt></ruby>"
    if word.startswith("お") and word == "お金":
        return "お<ruby>金<rt>かね</rt></ruby>"
    if word.startswith("あの方"):
        return "あの<ruby>方<rt>かた</rt></ruby>"
    if word.startswith("田中さん"):
        return "<ruby>田中<rt>たなか</rt></ruby>さん"
    if word == "代わりに":
        return "<ruby>代<rt>か</rt></ruby>わりに"
    if word == "思い出す":
        return "<ruby>思<rt>おも</rt></ruby>い<ruby>出<rt>だ</rt></ruby>す"
    if word == "間に合う":
        return "<ruby>間<rt>ま</rt></ruby>に<ruby>合<rt>あ</rt></ruby>う"
    if word == "買い物":
        return "<ruby>買<rt>か</rt></ruby>い<ruby>物<rt>もの</rt></ruby>"

    # Default fallback: full compound ruby
    return f"<ruby>{word}<rt>{reading}</rt></ruby>"

def build_review_300():
    items = []
    for num, kanji, examples in KANJI_300_DATA:
        ex_list = []
        for rd, word, word_rd in examples:
            ruby_str = make_ruby(kanji, word, word_rd)
            ex_list.append({
                "reading": rd,
                "example": word,
                "example_reading": word_rd,
                "example_ruby": ruby_str
            })
        items.append({
            "id": f"R{num:03d}",
            "number": num,
            "kanji": kanji,
            "examples": ex_list
        })

    out_file = Path(r"c:\Users\jaiad\Personal_Work_Related\Japanese Learning\nihongo-intermediate\data\kanji\review_300_n4_n5.json")
